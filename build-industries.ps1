# ---------- 3) complete sitemap ----------
$cats = (Get-Content $kwPath -Raw -Encoding UTF8 | ConvertFrom-Json).landingPages
$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('<?xml version="1.0" encoding="UTF-8"?>')
[void]$sb.AppendLine('<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">')
$core = @(
  @{l="$domain/";p="1.0";f="daily"}, @{l="$domain/buy.html";p="0.9";f="daily"},
  @{l="$domain/sell.html";p="0.9";f="weekly"}, @{l="$domain/how-it-works.html";p="0.6";f="monthly"},
  @{l="$domain/ecosystem.html";p="0.7";f="monthly"}
)
foreach ($c in $core) { [void]$sb.AppendLine("  <url><loc>$($c.l)</loc><lastmod>$updated</lastmod><changefreq>$($c.f)</changefreq><priority>$($c.p)</priority></url>") }
foreach ($i in $inds) { [void]$sb.AppendLine("  <url><loc>$domain/industries/$($i.slug).html</loc><lastmod>$updated</lastmod><changefreq>weekly</changefreq><priority>0.85</priority></url>") }
foreach ($c in $cats) { [void]$sb.AppendLine("  <url><loc>$domain/categories/$($c.slug).html</loc><lastmod>$updated</lastmod><changefreq>weekly</changefreq><priority>0.8</priority></url>") }
[void]$sb.AppendLine('</urlset>')
$sb.ToString() | Out-File -FilePath (Join-Path $root "sitemap.xml") -Encoding utf8

Write-Host ("-" * 60)
Write-Host ("Done. {0} industries + industries.js + sitemap ({1} URLs)." -f $inds.Count, ($core.Count + $inds.Count + $cats.Count)) -ForegroundColor Cyan
