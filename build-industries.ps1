<#
  ChemSurplus — industry build engine
  -------------------------------------------------------------
  Reads seo/industries.json and generates:
    * assets/js/industries.js          (runtime taxonomy — DO NOT hand-edit)
    * industries/<slug>.html           (per-industry SEO landing pages)
    * sitemap.xml                       (complete: core + categories + industries)

  Single source of truth = seo/industries.json (+ seo/keywords.json for category URLs).
  USAGE: powershell -ExecutionPolicy Bypass -File build-industries.ps1
#>

$ErrorActionPreference = "Stop"
$root    = $PSScriptRoot
$indPath = Join-Path $root "seo\industries.json"
$kwPath  = Join-Path $root "seo\keywords.json"
$supPath = Join-Path $root "seo\suppliers.json"
$indDir  = Join-Path $root "industries"
if (!(Test-Path $indDir)) { New-Item -ItemType Directory -Path $indDir | Out-Null }

$data    = Get-Content $indPath -Raw -Encoding UTF8 | ConvertFrom-Json
$sup     = Get-Content $supPath -Raw -Encoding UTF8 | ConvertFrom-Json
$inds    = $data.industries
$supMap  = @{}; foreach ($s in $sup.suppliers) { $supMap[$s.slug] = $s.name }
$domain  = "https://www.chemsurplus.com"
$updated = $data.meta.lastUpdated

Write-Host "ChemSurplus industry build ($($inds.Count) industries)" -ForegroundColor Cyan
Write-Host ("-" * 60)

# ---------- 1) runtime industries.js ----------
$runtime = $inds | ForEach-Object {
  [pscustomobject]@{
    slug=$_.slug; name=$_.name; icon=$_.icon; tagline=$_.tagline;
    categories=$_.categories; exampleChemicals=$_.exampleChemicals;
    suppliers=$_.suppliers; pains=$_.pains
  }
}
$json = $runtime | ConvertTo-Json -Depth 6
$jsHeader = "/* GENERATED by build-industries.ps1 from seo/industries.json - DO NOT EDIT. */`r`nconst INDUSTRIES = "
$jsFooter = ";`r`nfunction industryIconKey(slug){var i=INDUSTRIES.find(function(x){return x.slug===slug});return i?i.icon:'beaker';}"
($jsHeader + $json + $jsFooter) | Out-File -FilePath (Join-Path $root "assets\js\industries.js") -Encoding utf8
Write-Host "  [+] assets/js/industries.js" -ForegroundColor Green

# ---------- 1b) runtime suppliers.js (verified broker profiles) ----------
$supRuntime = @{}
foreach ($s in $sup.suppliers) {
  $supRuntime[$s.slug] = [pscustomobject]@{
    name=$s.name; tier="Verified broker"; since=$s.since;
    specialty=$s.specialty; regions=($s.regions -join " / "); url=$s.url
  }
}
$supJson = $supRuntime | ConvertTo-Json -Depth 5
$supJs = "/* GENERATED by build-industries.ps1 from seo/suppliers.json - DO NOT EDIT. */`r`n" +
         "const SUPPLIERS = $supJson;`r`n" +
         "function supplierInfo(slug){return SUPPLIERS[slug] || {name:'Verified supplier',tier:'Verified broker'};}`r`n" +
         "function supplierName(slug){return supplierInfo(slug).name;}"
$supJs | Out-File -FilePath (Join-Path $root "assets\js\suppliers.js") -Encoding utf8
Write-Host "  [+] assets/js/suppliers.js" -ForegroundColor Green

